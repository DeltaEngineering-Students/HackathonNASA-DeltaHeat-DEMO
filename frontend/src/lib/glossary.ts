// значущий / незначущий» next to p, «приземна температура повітря
// (на висоті 2 м)», «комірка сітки», «ділянка», …).
//
// Tone rules
// - Ukrainian, «ви», friendly and concrete; short sentences, everyday words. No English unless it is the name itself
//   (Landsat 8, NDVI, CMIP6, GHSL, Esri, SSP2‑4.5).
// - `short` ≤ 140 characters, one or two sentences: what it is + why it matters. An example beats a definition
//   («+8 °C — дахи й асфальт на 8° гарячіші за ліс»).
// - `more` (optional, ≤ 400 chars) is the «Детальніше» text: how it is computed, limits, honest caveats.
// - Decimal comma (0,05), °C with a space, U+2011 non-breaking hyphen inside SSP names, «…» quotes, ’ apostrophe.
// - Never promise precision we do not have: surface ≠ air, map ≠ card numbers, «суттєво» ≠ доведено.
// - No numbers that depend on a zone: the tooltip explains the term, the UI shows the value.

